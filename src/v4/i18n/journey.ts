/**
 * The journey (`pages/Journey.svelte`): the questions a DJ answers about
 * how they play, the path drawn from them, and the trail along the top of
 * a long page (`Trail.svelte`), in every language the site speaks. Edition
 * names, software and gear names stay as their makers write them.
 */

import { carried, type Lang } from "./strings";
import type { Card, EventKind, Gear, Interest, Plan, Question, Software, You } from "../journey";

export const TRAIL_SECTIONS = ["top", "highlights", "stems", "tour", "keys", "assistant", "karaoke", "visuals", "learn", "hardware", "community", "videos", "faq", "road", "download"] as const;
export type TrailSection = (typeof TRAIL_SECTIONS)[number];
export const ASKS = ["controller", "library", "price", "free", "stems", "karaoke", "journey"] as const;
export type Ask = (typeof ASKS)[number];

export interface JourneyWords {
  /** The bar's link. */
  nav: string;
  eyebrow: string;
  /** html */
  title: string;
  lead: string;
  begin: string;
  /** `{n}` of `{total}`. */
  progress: string;
  back: string;
  next: string;
  skip: string;
  finish: string;
  again: string;
  change: string;
  questions: Record<Question, { q: string; hint: string }>;
  options: {
    you: Record<You, string>;
    events: Record<EventKind, string>;
    gear: Record<Gear, string>;
    software: Record<Software, string>;
    plans: Record<Plan, string>;
    edition: Record<Interest, string>;
  };
  /** Who the journey is for, as its heading names them. */
  who: Record<You, string>;
  yours: string;
  /** `{who}`. */
  heading: string;
  forYou: string;
  why: Record<"hobbyist" | "apprentice" | "pro" | "karaoke" | "full" | "autopilot", string>;
  freeNote: string;
  editions: string;
  stepsTitle: string;
  /** Each step's title and line; `{software}` is the DJ's software. */
  cards: Record<Card | "try", { t: string; d: string }>;
  go: string;
  sound: string;
  soundLead: string;
  play: string;
  stop: string;
  noStyles: string;
  share: string;
  copied: string;
  kept: string;
  trail: {
    sections: Record<TrailSection, string>;
    next: string;
    map: string;
    asks: string;
    ask: Record<Ask, string>;
    top: string;
    where: string;
  };
}

